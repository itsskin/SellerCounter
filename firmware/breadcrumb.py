# "Хлебные крошки" — последняя известная активность платы, переживающая
# аппаратный сброс (в т.ч. watchdog, см. main.py WDT_TIMEOUT_MS). Обычный
# traceback через хардварный ресет не сохраняется — MicroPython просто
# перезапускается с нуля, никаких следов о том, что происходило до сброса.
# Этот файл — простейшая замена: пишем короткую строку "что сейчас делаем"
# ПЕРЕД каждой потенциально рискованной операцией (сетевой запрос,
# перерисовка экрана), без "после" (если бы после — то по зависанию не было
# бы разницы между "успело" и "нет). Если плата зависнет и watchdog её
# перезапустит, main.py при следующей загрузке печатает это в лог — видно,
# на чём застряло в прошлый раз, не гадаем вслепую.
#
# Пишем нечасто (только на реальных операциях, не на каждый чих) — flash
# переживает многие тысячи перезаписей одного файла без проблем при таком
# темпе, но всё равно незачем дёргать её на пустом месте.

import time

_PATH = "/last_activity.txt"


def mark(msg):
    try:
        with open(_PATH, "w") as f:
            f.write("%s %s" % (_now_hms(), msg))
    except OSError:
        pass


def read_last():
    """Что было записано ПЕРЕД последним сбросом (если было). None, если
    файла нет (например, самая первая загрузка вообще)."""
    try:
        with open(_PATH) as f:
            return f.read()
    except OSError:
        return None


def _now_hms():
    # Без часового пояса (просто UTC) — этот модуль не завязан на cfg, а
    # для диагностики "что и когда зависло" достаточно любого монотонного
    # представления времени, необязательно локального.
    _, _, _, hh, mm, ss, _, _ = time.gmtime()
    return "%02d:%02d:%02dZ" % (hh, mm, ss)
