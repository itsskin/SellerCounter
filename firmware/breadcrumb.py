# "Хлебные крошки" — последняя известная активность платы, переживающая
# аппаратный сброс (в т.ч. watchdog, см. main.py WDT_TIMEOUT_MS). Обычный
# traceback через хардварный ресет не сохраняется — MicroPython просто
# перезапускается с нуля, никаких следов о том, что происходило до сброса.
# Этот файл — простейшая замена: пишем короткую строку "что сейчас делаем"
# ПЕРЕД каждой потенциально рискованной операцией (сетевой запрос,
# перерисовка экрана), без "после" (если бы после — то по зависанию не было
# бы разницы между "успело" и "нет). Если плата зависнет и watchdog её
# перезапустит, main.py при следующей загрузке печатает это в лог — видно,
# на чём застряло в прошлый раз, не гадаем вслепую.
#
# Храним НЕСКОЛЬКО последних отметок (MAX_HISTORY), а не только самую
# свежую — HW-подтверждено, что одной было недостаточно: пока диагностика
# после сбоя успевает прочитать read_last(), плата уже вовсю грузится и
# сама же перезаписала её собственными метками ("connecting wifi (boot)" и
# т.п.), так что реальный момент зависания было не поймать. mark()
# ДОПИСЫВАЕТ новую отметку к уже лежащим на флеше (файл переживает сброс
# как есть) — то есть сразу после перезагрузки в истории видно и последние
# несколько шагов ДО сбоя, и первые шаги новой загрузки вперемешку, без
# путаницы, что где.
#
# Пишем нечасто (только на реальных операциях, не на каждый чих) — flash
# переживает многие тысячи перезаписей одного файла без проблем при таком
# темпе, но всё равно незачем дёргать её на пустом месте.

import time

_PATH = "/last_activity.txt"
# 30, не 8 — после того как _feed_watchdog (см. main.py) начал писать
# отдельную метку "wdt fed" каждые ~30с, 8 записей хватало всего на ~4
# минуты — ровно столько же, сколько интервал между пассивными проверками,
# так что буфер успевал целиком заполниться метками УЖЕ ПОСЛЕ перезагрузки
# раньше, чем кто-то успевал прочитать историю, и хвост ДО сбоя (самое
# ценное) вытеснялся. HW-подтверждено: именно так и произошло. 30 записей
# по ~30с — это ~15 минут вглубь, с большим запасом покрывает и интервал
# проверки, и типичное время до сброса.
MAX_HISTORY = 30


def _read_lines():
    with open(_PATH) as f:
        content = f.read()
    return [line for line in content.split("\n") if line]


def mark(msg):
    try:
        history = _read_lines()
    except OSError:
        history = []
    history.append("%s %s" % (_now_hms(), msg))
    history = history[-MAX_HISTORY:]
    try:
        with open(_PATH, "w") as f:
            f.write("\n".join(history))
    except OSError:
        pass


def read_last():
    """Самая свежая отметка ПЕРЕД последним сбросом (если была). None, если
    файла нет (например, самая первая загрузка вообще)."""
    try:
        lines = _read_lines()
    except OSError:
        return None
    return lines[-1] if lines else None


def read_history():
    """Последние MAX_HISTORY отметок, от старой к новой — не только НА ЧЁМ
    зависло, но и что происходило непосредственно перед этим (например,
    сколько маркетплейсов успело опроситься до того, как что-то зависло на
    следующем). Пустой список, если файла нет."""
    try:
        return _read_lines()
    except OSError:
        return []


_WDT_COUNT_PATH = "/wdt_reset_count.txt"


def read_wdt_reset_count():
    """Сколько раз плата перезагружалась именно по watchdog (reset_cause()
    == 3) за всё время — переживает сброс, в отличие от read_history()
    (тот хранит только последние MAX_HISTORY отметок, ~15 минут вглубь).
    Нужен для длинных неконтролируемых интервалов между проверками
    (например пока плата работает на отдельном блоке питания без
    подключения к компьютеру) — без него было бы невозможно узнать, сколько
    раз она упала, если сбросов было больше, чем помещается в историю.
    0, если файла нет (ещё ни одного watchdog-сброса не было с тех пор, как
    появился этот счётчик, или это вообще первая загрузка)."""
    try:
        with open(_WDT_COUNT_PATH) as f:
            return int(f.read().strip())
    except (OSError, ValueError):
        return 0


def mark_wdt_reset():
    """Вызывается из main.py ОДИН раз при загрузке, если machine.reset_cause()
    показывает, что этот запуск случился именно из-за watchdog. Увеличивает
    счётчик на 1 и возвращает новое значение."""
    count = read_wdt_reset_count() + 1
    try:
        with open(_WDT_COUNT_PATH, "w") as f:
            f.write(str(count))
    except OSError:
        pass
    return count


def reset_wdt_reset_count():
    """Обнулить счётчик — например перед началом контролируемого теста
    (скажем, сравнения количества сбросов на разных источниках питания),
    чтобы не мешать старые цифры с новыми."""
    try:
        with open(_WDT_COUNT_PATH, "w") as f:
            f.write("0")
    except OSError:
        pass


def _now_hms():
    # Без часового пояса (просто UTC) — этот модуль не завязан на cfg, а
    # для диагностики "что и когда зависло" достаточно любого монотонного
    # представления времени, необязательно локального.
    _, _, _, hh, mm, ss, _, _ = time.gmtime()
    return "%02d:%02d:%02dZ" % (hh, mm, ss)
